# ---------------- helpers ----------------
def set_font(run, size, bold=False, color=NAVY, italic=False):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = color


def textbox(slide, x, y, w, h, text, size=18, bold=False, color=NAVY, align=PP_ALIGN.LEFT,
            anchor=MSO_ANCHOR.TOP, italic=False):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = Inches(0.05)
    lines = text.split("\n")
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        r = p.add_run()
        r.text = line
        set_font(r, size, bold, color, italic)
    return tb


def bullets(slide, x, y, w, h, items, size=20, color=NAVY, gap=8):
    """items: list of str or (str, level). Level 1 is a sub-bullet."""
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = Inches(0.05)
    for i, it in enumerate(items):
        text, lvl = (it, 0) if isinstance(it, str) else it
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap)
        pPr = p._p.get_or_add_pPr()
        indent = 0.28 + 0.3 * lvl
        pPr.set("marL", str(int(Inches(indent))))
        pPr.set("indent", str(int(-Inches(0.28))))
        for tag in ("a:buNone", "a:buChar", "a:buAutoNum"):
            for e in pPr.findall(qn(tag)):
                pPr.remove(e)
        bu = etree.SubElement(pPr, qn("a:buChar"))
        bu.set("char", "•" if lvl == 0 else "–")
        # allow **bold** lead-in: "Lead: rest"
        if "||" in text:
            lead, rest = text.split("||", 1)
            r1 = p.add_run()
            r1.text = lead
            set_font(r1, size - 2 * lvl, True, color)
            r2 = p.add_run()
            r2.text = rest
            set_font(r2, size - 2 * lvl, False, color)
        else:
            r = p.add_run()
            r.text = text
            set_font(r, size - 2 * lvl, False, color)
    return tb


def picture(slide, name, x, y, w, h):
    """Place image fitted into the box (x,y,w,h inches), centered, aspect preserved."""
    path = os.path.join(IMG, name)
    with Image.open(path) as im:
        iw, ih = im.size
    scale = min(w / iw, h / ih)
    pw, ph = iw * scale, ih * scale
    slide.shapes.add_picture(path, Inches(x + (w - pw) / 2), Inches(y + (h - ph) / 2), Inches(pw), Inches(ph))


def rect(slide, x, y, w, h, fill=LIGHT, line=None, shape=MSO_SHAPE.ROUNDED_RECTANGLE, radius=0.08):
    s = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(2)
    if shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        s.adjustments[0] = radius
    s.shadow.inherit = False
    return s


